from __future__ import annotations

from collections.abc import Iterator
from contextlib import contextmanager
import os

CLI_PROVIDER_ENV_KEYS = ("AGENTKIT_CLOUD_PROVIDER", "CLOUD_PROVIDER")


@contextmanager
def preserve_cli_provider_environment() -> Iterator[None]:
    """Restore provider selection changed by direct CLI server calls."""

    original = {name: os.environ.get(name) for name in CLI_PROVIDER_ENV_KEYS}
    try:
        yield
    finally:
        for name, value in original.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value
